const r = require('express').Router();
const { auth, role } = require('../middleware/auth'), M = require('../models'), crud = require('../controllers/crud');
const sales = require('../controllers/salesController'), admin = require('../controllers/adminController'), pickup = require('../controllers/pickupController');
const adminOnly = role('Administrator');
const { staffOnly } = require('../middleware/auth');
const mount = (p, c) => { r.get(p, c.list); r.post(p, c.create); r.put(p + '/:id', c.update); r.delete(p + '/:id', adminOnly, c.remove); };
const history = require('../controllers/historyController');
const appointments = require('../controllers/appointmentController');

r.post('/auth/login', require('../controllers/authController').login);
r.post('/auth/signup', require('../controllers/authController').signup);
r.post('/public/appointments', require('../controllers/publicBookingController').create);
r.use(auth);
r.get('/customer/profile', require('../controllers/customerDashboardController').profile);
r.get('/customer/appointments', require('../controllers/customerDashboardController').appointments);
r.post('/customer/appointments', require('../controllers/customerDashboardController').createAppointment);
r.use(staffOnly);
r.get('/customers', history.customers);
r.get('/pets', history.pets);
r.get('/appointments', history.appointments);
mount('/customers', require('../controllers/customerController'));
mount('/pets', crud(M.Pet));
mount('/products', require('../controllers/productController'));
mount('/appointments', appointments);
mount('/pickups', crud(M.Pickup));
mount('/payments', crud(M.Payment));
r.post('/pickups/:id/release', pickup.release);
r.get('/low-stock', sales.lowStock);
r.get('/dashboard', sales.dashboard);
r.get('/sales', sales.history);
r.post('/sales/checkout', sales.checkout);
r.use('/users', adminOnly); mount('/users', require('../controllers/userController'));
r.use('/admin', adminOnly);
r.get('/admin/backups', admin.list); r.post('/admin/backup', admin.backup);
r.post('/admin/restore', admin.restore); r.get('/admin/logs', admin.logs);
module.exports = r;
